import {readFile, writeFile} from 'node:fs/promises';

const files=['world','simulation','city-art','actor-art','title-art','interface','main'];
const sources=await Promise.all(files.map(file=>readFile(new URL('../game/src/'+file+'.js',import.meta.url),'utf8')));
const modules=sources.map((source,i)=>{
  const imports=[];
  const body=source.replace(/^import\s*\{([^}]*)\}\s*from\s*'\.\/([^']+)\.js';\s*$/gm,(_,names,name)=>{
    imports.push('const {'+names+'} = modules['+JSON.stringify(name)+'];');
    return '';
  });
  const exports=[];
  const declarations=body.replace(/^export (const|function) (\w+)/gm,(_,kind,name)=>{
    exports.push(name);
    return kind+' '+name;
  });
  return 'modules['+JSON.stringify(files[i])+'] = (()=>{\n'+imports.join('\n')+'\n'+declarations.trim()+'\nreturn {'+exports.join(', ')+'};\n})();';
});
await writeFile(new URL('../game/offline.js',import.meta.url),
  '// Generated by scripts/build-offline.mjs.\n(()=>{\n"use strict";\nconst modules = {};\n'+modules.join('\n\n')+'\n})();\n');
